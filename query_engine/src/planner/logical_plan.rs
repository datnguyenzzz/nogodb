use std::sync::Arc;

use arrow::{
    array::ArrayRef,
    datatypes::{DataType, Schema},
};

use crate::planner::ast::operators::BinaryOperator;

/// Represents dynamic scalar literal values in expressions
pub enum ScalaValue {
    Null(DataType),
    Boolean(Option<bool>),
    Int32(Option<i32>),
    Int64(Option<i64>),
    Float64(Option<f64>),
    Utf8(Option<String>),
}

